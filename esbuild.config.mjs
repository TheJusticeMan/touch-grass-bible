import esbuild from "esbuild";
import { writeFileSync } from "fs";
import { resolve } from "path";
import process from "process";

const BUILD_INFO_MODULE = "@build-info";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this app
*/
`;
const prod = process.argv[2] === "production";
const buildTarget = process.env.APP_TARGET || "capacitor";
const enableExternalPlugins = process.env.ENABLE_EXTERNAL_PLUGINS === "true";
const targetVersion = process.env.npm_package_version || "0.0.0";
const frameworkLucidePath = resolve("packages/framework/node_modules/lucide/dist/esm/lucide.js");

if (!["electron", "capacitor"].includes(buildTarget)) {
  throw new Error(`Unsupported APP_TARGET: ${buildTarget}`);
}

function getBuildMetadata() {
  return {
    name: "Touch Grass Bible",
    description:
      "The bible app that keeps you grounded in the word while letting you into some functionality.",
    version: targetVersion,
    build: new Date().toISOString(),
    author: "Justice Vellacott",
    license: "MIT",
  };
}

function getBuildInfoModuleSource() {
  return [
    `const info = ${JSON.stringify(getBuildMetadata(), null, 2)} as const;`,
    "export default info;",
  ].join("\n");
}

/**
 * Generates `dist/index.html` with a loading shell and conditional CSP.
 */
function writeIndexHtml() {
  const cspContent = enableExternalPlugins
    ? "default-src 'self'; script-src 'self' 'unsafe-eval' blob:; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; connect-src 'self' http://localhost:11434 http://127.0.0.1:11434; worker-src blob:;"
    : "default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; connect-src 'self' http://localhost:11434 http://127.0.0.1:11434;";

  const output = [
    "<!doctype html>",
    '<html lang="en">',
    "  <head>",
    '    <meta charset="UTF-8" />',
    '<meta name="viewport" content="width=device-width, initial-scale=1.0, viewport-fit=cover" />',
    '    <meta name="apple-mobile-web-app-capable" content="yes" />',
    `    <meta http-equiv="Content-Security-Policy" content="${cspContent}" />`,
    '    <link rel="stylesheet" href="main.css" />',
    '    <link rel="icon" href="./favicon.ico" />',
    "    <title>Touch Grass Bible</title>",
    "    <style>",
    "      .loading-screen {",
    "        position: fixed;",
    "        inset: 0;",
    "        background-color: #444;",
    "        display: flex;",
    "        flex-direction: column;",
    "        justify-content: center;",
    "        align-items: center;",
    "        z-index: 1000;",
    "      }",
    "",
    "      .loading-spinner {",
    "        border: 8px solid #aaa;",
    "        border-radius: 50%;",
    "        width: 60px;",
    "        height: 60px;",
    "        animation: spin 2s linear infinite;",
    "      }",
    "",
    "      @keyframes spin {",
    "        0% {",
    "          border-radius: 100% 0%;",
    "          border-color: #fff #000;",
    "        }",
    "",
    "        25% {",
    "          border-radius: 0% 100%;",
    "        }",
    "",
    "        50% {",
    "          border-radius: 100% 0%;",
    "          border-color: #000 #fff;",
    "        }",
    "",
    "        75% {",
    "          border-radius: 0% 100%;",
    "        }",
    "",
    "        100% {",
    "          border-radius: 100% 0%;",
    "          border-color: #fff #000;",
    "        }",
    "      }",
    "",
    "      .loading-screen p {",
    "        margin-top: 20px;",
    "        font-size: 18px;",
    "        color: #ccc;",
    "      }",
    "    </style>",
    "  </head>",
    "  <body>",
    '    <div id="loadingScreen" class="loading-screen">',
    '      <div class="loading-spinner"></div>',
    '      <p id="loading-text">Loading... 0%</p>',
    "    </div>",
    "    <script>",
    "      let percent = 0;",
    '      const loadingText = document.getElementById("loading-text");',
    "",
    "      function updateLoadingText() {",
    "        percent++;",
    "        if (percent > 100) percent = 999;",
    "        if (loadingText) loadingText.textContent = `Loading... ${percent}%`;",
    "",
    "        setTimeout(() => {",
    "          if (Math.random() < 0.1) {",
    "            percent = Math.floor(Math.random() * 50 + 25);",
    "          }",
    "          if (loadingText?.isConnected) updateLoadingText();",
    "        }, 100);",
    "      }",
    "",
    "      updateLoadingText();",
    "    </script>",
    '    <script src="main.js"></script>',
    "  </body>",
    "</html>",
    "",
  ].join("\n");

  writeFileSync("dist/index.html", output);
}

const appContext = await esbuild.context({
  banner: {
    js: banner,
    css: banner,
  },
  entryPoints: ["src/main.ts"],
  bundle: true,
  outfile: "dist/main.js",
  metafile: prod,
  format: "iife",
  sourcemap: prod ? false : true,
  platform: "browser",
  logLevel: "info",
  minify: prod,
  treeShaking: true,
  define: {
    __ENABLE_EXTERNAL_PLUGINS__: JSON.stringify(enableExternalPlugins),
    __TG_PLATFORM_TARGET__: JSON.stringify(buildTarget),
  },
  plugins: [
    {
      name: "lucide-framework-alias",
      setup(build) {
        build.onResolve({ filter: /^lucide$/ }, () => ({
          path: frameworkLucidePath,
        }));
      },
    },
    {
      name: "metadata-writer",
      setup(build) {
        build.onResolve({ filter: /^@build-info$/ }, () => ({
          path: BUILD_INFO_MODULE,
          namespace: "tg-build-info",
        }));

        build.onLoad({ filter: /.*/, namespace: "tg-build-info" }, () => ({
          contents: getBuildInfoModuleSource(),
          loader: "ts",
        }));
      },
    },
    {
      name: "platform-virtual-module",
      setup(build) {
        build.onResolve({ filter: /^@platform$/ }, () => ({
          path: `@platform/${buildTarget}`,
          namespace: "tg-platform",
        }));

        build.onLoad({ filter: /.*/, namespace: "tg-platform" }, () => ({
          contents: [
            `export { createPlatformBridge } from "./${buildTarget}.ts";`,
            'export type { PlatformBridge, PlatformFileAdapter, PlatformStorageAdapter, PlatformTarget } from "./types.ts";',
          ].join("\n"),
          loader: "ts",
          resolveDir: resolve("src/platform"),
        }));
      },
    },
  ],
});

if (prod) {
  const result = await appContext.rebuild();

  // Write processed index.html with appropriate CSP
  writeIndexHtml();

  // 3. Write the metafile to disk
  if (result.metafile) {
    writeFileSync("meta.json", JSON.stringify(result.metafile, null, 2));
    console.log("Analysis metafile generated: meta.json");
  }

  console.log(`Built target: ${buildTarget} (external plugins: ${enableExternalPlugins})`);

  process.exit(0);
} else {
  await appContext.watch();
}
